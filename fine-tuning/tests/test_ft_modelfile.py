"""Fine-tuned Modelfile copies its base's settings (specs/finetuned-benchmark-run.md)."""

import sys
from pathlib import Path

import pytest

FT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(FT_ROOT / "scripts"))

import import_finetuned_to_ollama as imp  # noqa: E402

BASE = '''# Modelfile generated by "ollama show"
# To build a new Modelfile based on this, replace FROM with:
# FROM gemma3:4b

FROM /mnt/shared/ollama_models/blobs/sha256-aaa
TEMPLATE """{{- range $i, $_ := .Messages }}
FROM inside a template stays
{{ .Content }}{{ end }}"""
PARAMETER stop <end_of_turn>
PARAMETER temperature 1
SYSTEM """You are helpful."""
LICENSE """Some licence
FROM text in a licence stays"""
'''


def test_from_line_replaced_with_gguf():
    out = imp.build_ft_modelfile(BASE, Path("/g/model.Q4_K_M.gguf"))
    path_from = [line for line in out.splitlines() if line.startswith("FROM /")]
    assert path_from == ["FROM /g/model.Q4_K_M.gguf"]
    assert "sha256-aaa" not in out


def test_everything_else_kept():
    out = imp.build_ft_modelfile(BASE, Path("/g/m.gguf"))
    for kept in ("PARAMETER stop <end_of_turn>", "PARAMETER temperature 1", 'SYSTEM """You are helpful."""',
                 "FROM inside a template stays", "FROM text in a licence stays", "{{ .Content }}"):
        assert kept in out


def test_no_extra_parameters_added():
    out = imp.build_ft_modelfile(BASE, Path("/g/m.gguf"))
    assert "num_ctx" not in out and "num_predict" not in out


def test_two_from_lines_become_one():
    base = "FROM /blobs/model\nFROM /blobs/projector\nPARAMETER temperature 1\n"
    out = imp.build_ft_modelfile(base, Path("/g/m.gguf"))
    assert out.count("FROM ") == 1


def test_missing_from_raises():
    with pytest.raises(ValueError, match="FROM"):
        imp.build_ft_modelfile("PARAMETER temperature 1\n", Path("/g/m.gguf"))


def test_settings_body_ignores_from_and_comments():
    ft = imp.build_ft_modelfile(BASE, Path("/g/m.gguf"))
    assert imp.modelfile_settings(ft) == imp.modelfile_settings(BASE)
    assert imp.modelfile_settings(BASE) != imp.modelfile_settings(BASE.replace("temperature 1", "temperature 0.8"))


def test_settings_body_keeps_from_inside_blocks():
    assert "FROM inside a template stays" in imp.modelfile_settings(BASE)


def test_settings_ignore_directive_order():
    first = "FROM /a\nPARAMETER top_p 0.95\nPARAMETER stop <end_of_turn>\n"
    second = "FROM /b\nPARAMETER stop <end_of_turn>\nPARAMETER top_p 0.95\n"
    assert imp.modelfile_settings(first) == imp.modelfile_settings(second)


def test_settings_keep_blocks_whole_when_sorting():
    text = 'TEMPLATE """line one\nline two"""\nPARAMETER a 1\n'
    assert 'TEMPLATE """line one\nline two"""' in imp.modelfile_settings(text)
